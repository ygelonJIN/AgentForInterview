def contains_any(text: str, terms) -> bool:
    return any(term in text for term in terms)


def matched_terms(text: str, terms):
    """返回命中的词，按出现位置排序；被更长命中覆盖的短词不回传。

    "跑步鞋" 只算命中一次（跑鞋/跑步鞋/鞋 三选一取最长），
    否则一个品类名会被重复计数。
    """
    spans = []
    for term in terms:
        start = text.find(term)
        if start < 0:
            continue
        spans.append((start, start + len(term), term))
    spans.sort(key=lambda item: (item[0], -(item[1] - item[0])))
    kept = []
    last_end = -1
    for start, end, term in spans:
        if start < last_end:
            continue
        kept.append(term)
        last_end = end
    return kept


def is_negated(text: str, term: str, window: int = 4) -> bool:
    """词前面 4 个字里出现否定词 -> 视为被否定（"不要帐篷"）。"""
    index = text.find(term)
    if index < 0:
        return False
    before = text[max(0, index - window):index]
    return any(prefix in before for prefix in NEGATION_PREFIXES)
